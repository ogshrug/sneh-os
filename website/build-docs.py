def mark_svg():
    s = open(os.path.join(HERE, "index.html"), encoding="utf-8").read()
    return re.search(r'<svg class="mark".*?</svg>', s, re.S).group(0)


def build():
    mark = mark_svg()
    rendered = {n: render(n) for n, _, _ in PAGES}
    index = [{"f": f"{n}.html", "n": t, "e": [{"t": t, "a": "top"}] + rendered[n][3]} for n, t, _ in PAGES]
    out = {}
    for i, (n, t, _) in enumerate(PAGES):
        _, body, heads, _ = rendered[n]
        nav = "".join(
            f'<a class="current" href="{m}.html" aria-current="page">{html.escape(tt)}</a><ul>'
            + "".join(f'<li class="l{lv}"><a href="#{hid}">{html.escape(txt)}</a></li>' for lv, hid, txt in heads if lv == 2)
            + "</ul>" if m == n else f'<a href="{m}.html">{html.escape(tt)}</a>'
            for m, tt, _ in PAGES)
        toc = ("<p>On this page</p><ul>" + "".join(
            f'<li class="l{lv}"><a href="#{hid}">{html.escape(txt)}</a></li>' for lv, hid, txt in heads) + "</ul>") if heads else ""
        prev = PAGES[i - 1] if i else None
        nxt = PAGES[i + 1] if i + 1 < len(PAGES) else None
        pager = '<nav class="pager">' + (
            f'<a class="prev" href="{prev[0]}.html"><span>Previous</span>{html.escape(prev[1])}</a>' if prev else "<span></span>") + (
            f'<a class="next" href="{nxt[0]}.html"><span>Next</span>{html.escape(nxt[1])}</a>' if nxt else "") + "</nav>"
        out[f"{n}.html"] = page(n, t, body.replace("<h2", "\n<h2"), heads, nav, toc, pager, mark, index).replace(
            '<article class="docs-body">', '<article class="docs-body" id="top">')
    cards = "".join(f'<a class="card doc-card" href="{n}.html"><h3>{html.escape(t)}</h3><p>{html.escape(d)}</p></a>' for n, t, d in PAGES)
    nav = "".join(f'<a href="{n}.html">{html.escape(t)}</a>' for n, t, _ in PAGES)
    body = f'<p class="lede-docs">Everything about installing, using and changing Sneh. Press <kbd>/</kbd> to search.</p>\n<div class="grid two doc-cards">{cards}</div>'
    out["index.html"] = page("index", "Documentation", body, [], nav, "", "", mark, index)
    return out


def main():
    out = build()
    if "--check" in sys.argv:
        stale = [f for f, s in out.items()
                 if not os.path.exists(os.path.join(OUT, f)) or open(os.path.join(OUT, f), encoding="utf-8").read() != s]
        if stale:
            print("website/docs is out of date; run: python3 website/build-docs.py  (" + ", ".join(stale) + ")")
            sys.exit(1)
        print("website/docs is up to date")
        return
    os.makedirs(OUT, exist_ok=True)
    for f, s in out.items():
        with open(os.path.join(OUT, f), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(s)
    print(f"wrote {len(out)} pages to {OUT}")


if __name__ == "__main__":
    main()
